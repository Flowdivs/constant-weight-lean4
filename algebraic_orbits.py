N_BITS = 18
WEIGHT = 5
MAX_OVERLAP = 2
CACHE_FILE = "compat_graph.bin"
C17_JSON = "orbits_c17.json"
C18_JSON = "orbits_c18.json"
C3_JSON = "orbits_c3.json"
SUMMARY_JSON = "orbits_summary.json"

def generate_all_words():
    """Generate all C(18, 5) = 8,568 codewords as 32-bit integers."""
    return [sum(1 << i for i in comb) for comb in itertools.combinations(range(N_BITS), WEIGHT)]

def load_or_build_compat_masks(words):
    """Load or precompute the compatibility bitmasks for all words."""
    N = len(words)
    byte_len = (N + 7) // 8
    if os.path.exists(CACHE_FILE):
        with open(CACHE_FILE, "rb") as f:
            raw = f.read()
        return [int.from_bytes(raw[i*byte_len:(i+1)*byte_len], "little") for i in range(N)]

    print(f"[Init] Precomputing compatibility graph for {N} words...", flush=True)
    t0 = time.time()
    adj = [0] * N
    raw = bytearray(N * byte_len)
    for i in range(N):
        wi = words[i]
        mask = 0
        for j in range(N):
            if (wi & words[j]).bit_count() <= MAX_OVERLAP:
                mask |= (1 << j)
        adj[i] = mask
        raw[i*byte_len:(i+1)*byte_len] = mask.to_bytes(byte_len, "little")

    with open(CACHE_FILE, "wb") as f:
        f.write(raw)
    print(f"[Init] Saved cache to {CACHE_FILE} in {time.time()-t0:.2f}s", flush=True)
    return adj

def compat(w1, w2):
    """Check whether two codewords satisfy distance >= 6 (overlap <= 2)."""
    return (w1 & w2).bit_count() <= MAX_OVERLAP

