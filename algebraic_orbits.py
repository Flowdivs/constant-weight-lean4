def export_c17_orbit_data(words):
    """Deep analysis and export of C_17 orbits."""
    N = len(words)
    word_to_idx = {w: i for i, w in enumerate(words)}
    orbits = compute_orbits(words, [perm_c17])
    val = filter_internally_valid_orbits(orbits)
    adj = compute_orbit_compatibility_matrix(val)
    K = len(val)

    # Find 4-cliques
    cliques_4 = []
    for i in range(K):
        nbrs_i = [j for j in range(i + 1, K) if adj[i][j]]
        for idx_j, j in enumerate(nbrs_i):
            nbrs_ij = [l for l in nbrs_i[idx_j + 1:] if adj[j][l]]
            for idx_l, l in enumerate(nbrs_ij):
                nbrs_ijl = [m for m in nbrs_ij[idx_l + 1:] if adj[l][m]]
                for m in nbrs_ijl:
                    cliques_4.append([i, j, l, m])

    val_export = []
    for idx_in_val, (orig_idx, orb) in enumerate(val):
        u0 = orb[0]
        has_inf = bool((u0 >> 17) & 1)
        pts = [bit for bit in range(18) if (u0 >> bit) & 1]
        val_export.append({
            "val_index": idx_in_val,
            "orig_orbit_index": orig_idx,
            "representative_int": u0,
            "representative_hex": hex(u0),
            "points": pts,
            "has_inf": has_inf,
            "word_indices": [word_to_idx[w] for w in orb],
            "codewords_hex": [hex(w) for w in orb]
        })

    clusters_68 = []
    for c_idx, clq in enumerate(cliques_4):
        code_indices = []
        for oi in clq:
            code_indices.extend(val_export[oi]["word_indices"])
        clusters_68.append({
            "cluster_id": c_idx,
            "orbit_indices": clq,
            "size": len(code_indices),
            "codeword_indices": code_indices,
            "codewords_hex": [hex(words[idx]) for idx in code_indices],
            "base_blocks": [val_export[oi]["points"] for oi in clq]
        })

    out_data = {
        "group": "C_17",
        "order": 17,
        "total_words": N,
        "valid_orbit_count": K,
        "orbit_size": 17,
        "density": sum(adj[i][j] for i in range(K) for j in range(i+1, K)) / (K*(K-1)//2),
        "orbits": val_export,
        "compat_matrix": adj,
        "size_68_clusters": clusters_68
    }

    with open(C17_JSON, "w") as f:
        json.dump(out_data, f, indent=2)
    return out_data

