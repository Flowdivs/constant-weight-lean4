def compute_orbits(words, generators):
    """Partition words into orbits under the group generated by `generators`."""
    visited = set()
    orbits = []
    for w in words:
        if w in visited:
            continue
        orb = []
        queue = [w]
        visited.add(w)
        while queue:
            cur = queue.pop()
            orb.append(cur)
            for gen in generators:
                nxt = gen(cur)
                if nxt not in visited:
                    visited.add(nxt)
                    queue.append(nxt)
        orbits.append(orb)
    return orbits

def filter_internally_valid_orbits(orbits):
    """
    Filter orbits that are internally valid (minimum Hamming distance >= 6).
    Optimization: For any transitive group action, u0 is compatible with all v in orb
    if and only if every pair in orb is compatible.
    """
    valid = []
    for idx, orb in enumerate(orbits):
        u0 = orb[0]
        if all(compat(u0, orb[k]) for k in range(1, len(orb))):
            valid.append((idx, orb))
    return valid

def compute_orbit_compatibility_matrix(valid_orbits):
    """
    Compute K x K boolean compatibility matrix among valid orbits.
    Two orbits are compatible iff u0 in orb_i is compatible with ALL v in orb_j.
    """
    K = len(valid_orbits)
    adj = [[False] * K for _ in range(K)]
    for i in range(K):
        adj[i][i] = True
        u0 = valid_orbits[i][1][0]
        for j in range(i + 1, K):
            orb_j = valid_orbits[j][1]
            if all(compat(u0, v) for v in orb_j):
                adj[i][j] = True
                adj[j][i] = True
    return adj

def solve_max_orbit_clique(valid_orbits, adj_matrix):
    """
    Solve maximum clique on the orbit compatibility graph using PySAT CaDiCaL.
    Returns (best_clique_indices, total_codewords).
    """
    K = len(valid_orbits)
    if K == 0:
        return [], 0
    best_clique = []
    for target in range(1, K + 1):
        cnf = CNF()
        for i in range(K):
            for j in range(i + 1, K):
                if not adj_matrix[i][j]:
                    cnf.append([-(i + 1), -(j + 1)])
        cnf.extend(CardEnc.atleast(lits=list(range(1, K + 1)), bound=target, top_id=K))
        with Solver(name="cadical195", bootstrap_with=cnf) as solver:
            if solver.solve():
                model = solver.get_model()
                best_clique = [i for i in range(K) if model[i] > 0]
            else:
                break
    total_codewords = sum(len(valid_orbits[i][1]) for i in best_clique)
    return best_clique, total_codewords

