def analyze_all_groups(words):
    """Run full comparative analysis of all relevant algebraic groups."""
    groups = [
        ("C_17", [perm_c17], "Cyclic action on Z_17 + {inf}"),
        ("D_17", [perm_c17, perm_refl17], "Dihedral action on Z_17 + {inf}"),
        ("F_68", [perm_c17, perm_mult4_17], "Frobenius group order 68"),
        ("AGL(1,17)", [perm_c17, perm_mult3_17], "Affine General Linear group order 272"),
        ("C_18", [perm_c18], "Cyclic action on Z_18"),
        ("D_18", [perm_refl18, perm_c18], "Dihedral action on Z_18"),
        ("C_3", [perm_c3], "Cyclic subgroup order 3 (divisor of 69)"),
    ]

    summary = {}
    print("=" * 75)
    print("ALGEBRAIC GROUP ACTION AUDIT FOR A(18, 6, 5)")
    print("=" * 75)

    for name, gens, desc in groups:
        t0 = time.time()
        orbits = compute_orbits(words, gens)
        sizes = defaultdict(int)
        for orb in orbits:
            sizes[len(orb)] += 1

        val = filter_internally_valid_orbits(orbits)
        val_sizes = defaultdict(int)
        for idx, orb in val:
            val_sizes[len(orb)] += 1

        adj = compute_orbit_compatibility_matrix(val)
        K = len(val)
        edges = sum(adj[i][j] for i in range(K) for j in range(i + 1, K))
        density = edges / (K * (K - 1) // 2) if K > 1 else 0

        if K <= 300:
            best_clq, max_cwords = solve_max_orbit_clique(val, adj)
        else:
            best_clq, max_cwords = [], 0

        el = time.time() - t0
        print(f"Group: {name:<10} | Orbits: {len(orbits):<4} | Valid: {len(val):<4} | Max Orbit Clique: {len(best_clq)} ({max_cwords} words) in {el:.2f}s")
        print(f"  Description: {desc}")
        print(f"  Orbit sizes: {dict(sizes)} | Valid sizes: {dict(val_sizes)}")
        print(f"  Compatible pairs: {edges} (density: {density:.4f})")
        print("-" * 75)

        summary[name] = {
            "total_orbits": len(orbits),
            "orbit_sizes": dict(sizes),
            "valid_orbits": len(val),
            "valid_orbit_sizes": dict(val_sizes),
            "compatible_pairs": edges,
            "density": float(density),
            "max_orbit_clique_size": len(best_clq),
            "max_codewords": max_cwords,
        }

    with open(SUMMARY_JSON, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"[Export] Wrote full comparative audit to {SUMMARY_JSON}", flush=True)

