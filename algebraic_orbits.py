def perm_c17(w):
    """C_17: x -> (x + 1) mod 17 for x < 17; 17 -> 17 (fixed point)."""
    res = 0
    for i in range(17):
        if (w >> i) & 1:
            res |= (1 << ((i + 1) % 17))
    if (w >> 17) & 1:
        res |= (1 << 17)
    return res

def perm_refl17(w):
    """Reflection in D_17: x -> (-x) mod 17; 17 -> 17."""
    res = 0
    for i in range(17):
        if (w >> i) & 1:
            res |= (1 << ((-i) % 17))
    if (w >> 17) & 1:
        res |= (1 << 17)
    return res

