"""
Algebraic Orbit Decomposition and Compatibility Engine for A(18, 6, 5)
Partitions C(18, 5) = 8,568 words into orbits under algebraic group actions:
- Cyclic action C_17 on Z_17 + {inf} (with coordinate 17 fixed)
- Cyclic action C_18 on Z_18
- Dihedral action D_18 on Z_18
- Dihedral action D_17 on Z_17 + {inf}
- Frobenius group AGL(1, 17) and F_68 on Z_17 + {inf}
- Cyclic subgroup C_3 on Z_18 (candidate for size 69 = 23 * 3)

Computes:
1. Exact orbit decomposition and orbit sizes.
2. Internal validity (self-compatibility: all intra-orbit distances >= 6, max overlap <= 2).
3. Orbit compatibility matrix (inter-orbit mutual compatibility).
4. Maximum clique of compatible orbits (exact algebraic subcodes).
5. Candidate extension pools for SAT completion.
"""

